CREATE TABLE dbo.CNT
(
    NOwner      INT          NOT NULL CONSTRAINT PK_CNT PRIMARY KEY,
    Owner       VARCHAR(50)  NULL,
    Company     VARCHAR(150) NULL,
    IsActive    BIT          NOT NULL CONSTRAINT DF_CNT_IsActive DEFAULT (1),
    PostalIndex VARCHAR(12)  NULL,
    Region      VARCHAR(50)  NULL,
    City        VARCHAR(24)  NULL,
    Street      VARCHAR(64)  NULL,
    House       VARCHAR(10)  NULL,
    Flat        VARCHAR(25)  NULL,
    Floor       SMALLINT     NULL
);
GO

CREATE TABLE dbo.ITEM
(
    Item   INT         NOT NULL CONSTRAINT PK_ITEM PRIMARY KEY,
    Name   VARCHAR(50) NOT NULL CONSTRAINT UQ_ITEM_Name UNIQUE,
    Volume FLOAT       NULL
);
GO

CREATE TABLE dbo.OPER
(
    Id   INT         NOT NULL CONSTRAINT PK_OPER PRIMARY KEY,
    Name VARCHAR(50) NOT NULL CONSTRAINT UQ_OPER_Name UNIQUE,
    sign SMALLINT    NOT NULL
);
GO

CREATE TABLE dbo.DOC
(
    NDoc        INT          NOT NULL CONSTRAINT PK_DOC PRIMARY KEY,
    Doc         INT          NULL,
    Receive     INT          NULL CONSTRAINT FK_DOC_Receive   REFERENCES dbo.CNT (NOwner),
    Consignee   INT          NULL CONSTRAINT FK_DOC_Consignee REFERENCES dbo.CNT (NOwner),
    Ship        INT          NULL CONSTRAINT FK_DOC_Ship      REFERENCES dbo.CNT (NOwner),
    Comment     VARCHAR(255) NULL,
    UserName    VARCHAR(16)  NULL,
    IsShipped   BIT          NOT NULL CONSTRAINT DF_DOC_IsShipped  DEFAULT (1),
    IsPrint     BIT          NOT NULL CONSTRAINT DF_DOC_IsPrint    DEFAULT (0),
    IsRegister  BIT          NOT NULL CONSTRAINT DF_DOC_IsRegister DEFAULT (0),
    Total       MONEY        NULL,
    CreatDate   DATETIME     NOT NULL,
    AccountDate DATETIME     NULL,
    PayDate     DATETIME     NULL
);
GO

CREATE TABLE dbo.DOCSTR
(
    NDoc  INT   NOT NULL CONSTRAINT FK_DOCSTR_NDoc REFERENCES dbo.DOC  (NDoc),
    Item  INT   NOT NULL CONSTRAINT FK_DOCSTR_Item REFERENCES dbo.ITEM (Item),
    Oper  INT   NOT NULL CONSTRAINT FK_DOCSTR_Oper REFERENCES dbo.OPER (Id),
    Qty   INT   NOT NULL,
    Price MONEY NULL,
    Cost  MONEY NULL,
    CONSTRAINT PK_DOCSTR PRIMARY KEY (NDoc, Item, Oper)
);
GO

CREATE TABLE dbo.Phones
(
    Id       INT          NOT NULL CONSTRAINT PK_Phones PRIMARY KEY,
    NOwner   INT          NULL CONSTRAINT FK_Phones_NOwner REFERENCES dbo.CNT (NOwner),
    CodeCity INT          NULL,
    Phone    VARCHAR(10)  NULL,
    Type     INT          NULL,
    Comment  VARCHAR(254) NULL,
    Priority INT          NULL,
    Solid    NVARCHAR(16) NULL
);
GO

CREATE INDEX IX_DOC_Receive ON dbo.DOC (Receive, CreatDate) INCLUDE (AccountDate, IsShipped, IsRegister);
GO

CREATE INDEX IX_Phones_NOwner ON dbo.Phones (NOwner, Priority, Id) INCLUDE (Solid);
GO

